export const PALETTE_BY_ID = new Map(FLAT_UI_PALETTES.map((p) => [p.id, p]))
/** Throws rather than returning undefined — a page file naming a palette that
 *  does not exist is a build-time mistake, not a runtime state. */
export function palette(id: string): Palette {
  const found = PALETTE_BY_ID.get(id)
  if (!found) throw new Error(`Unknown palette "${id}"`)
  return found
}
